  /* 「常用指令模板」（可复制，属于内容不是过程） */
  function esc(s) {
    return String(s == null ? '' : s)
      .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
  }
  function cmdBox() {
    const items = ((typeof DATA !== 'undefined' ? DATA : {}).commands || {}).items || [];
    if (!items.length) return '';
    return `<section class="mxcmd" data-mod="mx-cmds">
      <div class="mxcmd__h">「常用指令模板」<span>${items.length} 条 · 点复制直接发我，变量填一下就跑</span></div>
      ${items.map((c, i) => `<div class="mxcmd__i">
        <div class="mxcmd__t">${esc(c.t)}<button class="btn btn--solid" data-copy="${i}">复制</button></div>
        <pre class="mxcmd__b" id="cmd${i}">${esc(c.body)}</pre>
      </div>`).join('')}
    </section>`;
  }

