  /* 七条动作的反馈 / 替换入口（只绑一次，走事件委托，重绘也不会丢） */
  function wireFb() {
    if (wireFb._on) return;
    wireFb._on = 1;
    document.addEventListener('click', e => {
      const b = e.target.closest('[data-mvfb]');
      if (b) {
        const wrap = b.closest('.bzmfb');
        const box = wrap.querySelector('.bzmfb__box');
        const ta = box.querySelector('textarea');
        box.hidden = false;
        /* 预置一句，她改不改都行；已经写了东西就不覆盖 */
        if (!ta.value.trim()) ta.value = b.dataset.pre || '';
        ta.focus();
        try { ta.setSelectionRange(ta.value.length, ta.value.length); } catch (err) {}
        return;
      }
      const go = e.target.closest('[data-mvgo]');
      if (!go) return;
      const i = +go.dataset.mvgo;
      const m = CURRENT_MOVES[i] || {};
      const box = go.closest('.bzmfb__box');
      const ta = box.querySelector('textarea');
      const txt = ta.value.trim();
      if (!txt || txt.length < 4) { window.FB && FB.toast('写一句再提交，一句就够'); return; }
      if (!window.FB) return;
      const ok = FB.submit({
        kind: 'add', view: '我的业务基本盘',
        topic: 'move-' + i, topicName: '策略动作 ' + (m.p || '') + '：' + String(m.t || '').slice(0, 18),
        text: txt
      });
      if (!ok) return;                     /* 本批满了，FB 会自己提示 */
      ta.value = '';
      box.hidden = true;
      const tag = document.createElement('span');
      tag.className = 'bzmfb__ok';
      tag.textContent = '已记下，下一版按你这句改';
      box.parentElement.querySelector('.bzmfb__r').appendChild(tag);
      setTimeout(() => tag.remove(), 4000);
    });
  }

